"""[EN-FR fork] Settings pages translation.

    python3 tools/i18n/build.py            # regenerate tools/settings_i18n.js
    python3 tools/i18n/build.py --missing  # list Japanese texts without translation

dict.json maps each Japanese text (whitespace collapsed) to {"fr": ..., "en": ...}.
After an upstream merge, run --missing, add the new entries to dict.json, then
run the script without option and commit both files.
"""
import json
import sys
from pathlib import Path

ICI = Path(__file__).resolve().parent
RACINE = ICI.parent.parent
PAGES = [
    RACINE / "tools/settings.html",
    RACINE / "tools/settings_common.js",
    RACINE / "components/wifi_config_service/web/settings_wifi.html",
    RACINE / "docs/index.html",
]

sys.path.insert(0, str(ICI))
from extract import extract  # noqa: E402


def main():
    d = json.loads((ICI / "dict.json").read_text(encoding="utf-8"))
    if "--missing" in sys.argv:
        manque = sorted({k for p in PAGES for k in extract(str(p))} - set(d))
        print(json.dumps(manque, ensure_ascii=False, indent=1))
        print(f"{len(manque)} texte(s) sans traduction", file=sys.stderr)
        return
    for k, v in d.items():
        if not v.get("fr") or not v.get("en"):
            sys.exit(f"traduction incomplete : {k!r}")
    compact = json.dumps(d, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    moteur = (ICI / "engine.js").read_text(encoding="utf-8")
    assert "/*{{DICT}}*/{}" in moteur
    sortie = moteur.replace("/*{{DICT}}*/{}", compact.replace("</", "<\\/"))
    entete = "// GENERATED by tools/i18n/build.py from tools/i18n/engine.js + dict.json. Do not edit.\n"
    (RACINE / "tools/settings_i18n.js").write_text(entete + sortie, encoding="utf-8")
    print(f"tools/settings_i18n.js : {len(d)} entrees, {len(sortie) // 1024} Kio")


if __name__ == "__main__":
    main()
